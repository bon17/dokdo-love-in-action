/* 낱말 찾기 틀: 긴 낱말부터 찾고, 띄어쓰기 자리는 줄바꿈 없는 공백도 받아 준다. */
const GLOSS_FORM = {};
for (const [k, g] of Object.entries(GLOSS)) { GLOSS_FORM[k] = k; for (const a of g.a || []) GLOSS_FORM[a] = k; }
const GLOSS_RE = new RegExp(Object.keys(GLOSS_FORM).sort((a, b) => b.length - a.length)
  .map(f => f.replace(/[.*+?^${}()|[\]\\]/g, '\\$&').replace(/ /g, '[\\s\\u00a0]')).join('|'), 'g');
const glossKey = m => GLOSS_FORM[m.replace(/\u00a0/g, ' ')];

/* 글을 조각으로 나눈다: [{t}, {t, k}] — k가 있으면 풀이가 있는 낱말.
   같은 글 덩어리(seen) 안에서는 처음 나온 한 번만 밑줄을 긋고, 『책 이름』 「법 이름」 안은 건너뛴다. */
function glossSplit(s, seen = new Set()) {
  s = String(s);
  const skip = [];
  for (const re of [/『[^』]*』/g, /「[^」]*」/g]) { let m; while ((m = re.exec(s))) skip.push([m.index, m.index + m[0].length]); }
  const out = [];
  let last = 0, m;
  GLOSS_RE.lastIndex = 0;
  while ((m = GLOSS_RE.exec(s))) {
    const k = glossKey(m[0]), i = m.index;
    if (!k || seen.has(k) || skip.some(([a, b]) => i >= a && i < b)) continue;
    if (GLOSS[k].nb && i > 0 && GLOSS[k].nb.includes(s[i - 1])) { GLOSS_RE.lastIndex = i + 1; continue; }
    seen.add(k);
    if (i > last) out.push({ t: s.slice(last, i) });
    out.push({ t: m[0], k });
    last = i + m[0].length;
  }
  if (last < s.length) out.push({ t: s.slice(last) });
  return out;
}
/* 밑줄 낱말을 누르면 풀이를 띄운다. 대사 창 안에서는 대사가 넘어가지 않게 막고,
   고르는 문장(옛 문서 찾기)이나 조각 안에서는 원래 하던 일(고르기)도 그대로 한다. */
function glossSpan(k) {
  const sp = el('span', { class: 'gl' });
  sp.dataset.k = k;
  sp.addEventListener('click', e => { Sound.sfx('tap'); glossShow(k, sp); if (sp.closest('#dialog .dlg')) e.stopPropagation(); });
  return sp;
}
/* 밑줄 낱말이 들어간 글 조각 (el의 자식으로 넣어 쓴다) */
function gtext(s, seen) {
  const f = document.createDocumentFragment();
  for (const sg of glossSplit(ko(String(s == null ? '' : s)), seen)) {
    if (sg.k) { const sp = glossSpan(sg.k); sp.textContent = sg.t; f.append(sp); } else f.append(sg.t);
  }
  return f;
}
let glossPop = null, glossSwallow = 0;
function glossClose() { if (glossPop) { glossPop.remove(); glossPop = null; } }
function glossShow(k, anchor) {
  glossClose();
  const g = GLOSS[k];
  if (!g) return;
  const pop = el('div', { class: 'glpop' }, el('div', { class: 'gw' }, k, g.h ? el('span', { class: 'gh', text: g.h }) : null), el('div', { class: 'gd', text: g.d }),
    el('div', { class: 'gx', text: '아무 곳이나 누르면 닫혀요' }));
  L.toast.append(pop);
  glossPop = pop;
  const r = anchor.getBoundingClientRect(), a = APP.getBoundingClientRect();
  const x = (r.left + r.width / 2 - a.left) / SCALE, top = (r.top - a.top) / SCALE, bot = (r.bottom - a.top) / SCALE;
  const w = pop.offsetWidth, h = pop.offsetHeight;
  pop.style.left = clamp(x - w / 2, 12, W - w - 12) + 'px';
  pop.style.top = (top - h - 12 >= 70 ? top - h - 12 : Math.min(bot + 12, H - h - 8)) + 'px';
}
